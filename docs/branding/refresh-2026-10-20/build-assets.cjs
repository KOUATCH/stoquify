// Offline vector asset authoring. Uses the existing licensed Manrope font.
// NODE_PATH may point to the Codex bundled packages; no application config is loaded.
const fs = require("node:fs");
const path = require("node:path");
const { Path2D } = require("@napi-rs/canvas");
const sharp = require("sharp");

const root = path.resolve(__dirname, "../../..");
const assets = path.join(root, "public/brand");
const blue = "#2f7df6";
const ink = "#132028";
// Three equal units; 120-degree rotation connects stock, sales and finance.
const unit = "M32 4.73Q35 3 38 4.73L49 11.08Q52 12.81 52 16.27V35L43 40.2L35 35.58V26.92Q35 23.46 32 21.73L24 17.11L16 21.73V16.27Q16 12.81 19 11.08Z";
const rotateUnit = (outline, degrees) => {
  const radians = degrees * Math.PI / 180;
  const c = Math.cos(radians), s = Math.sin(radians);
  // Move each unit outward to keep the three channels open at small sizes.
  return new Path2D(outline).transform({ a: c, b: s, c: -s, d: c, e: 35 - 35 * c + 38 * s, f: 35 - 35 * s - 38 * c }).toSVGString();
};
const mark = [0, 120, 240].map(degrees => rotateUnit(unit, degrees)).join(" ");
const topFace = "M32 4.73Q35 3 38 4.73L49 11.08Q51 12.24 51.67 14.17L43 19.18L24 8.19Z";
const sideFace = "M43 19.18L51.67 14.17Q52 15.1 52 16.27V35L43 40.2Z";
const faces = [
  { path: [0, 120, 240].map(degrees => rotateUnit(topFace, degrees)).join(" "), token: "--product-brand-strong", fallback: "#5796ff" },
  { path: [0, 120, 240].map(degrees => rotateUnit(sideFace, degrees)).join(" "), token: "--product-brand-action-hover", fallback: "#1d4ed8" },
];
const title = "<title>Stoquify</title>";
const svg = (w, h, body) => `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" role="img" aria-label="Stoquify">${title}${body}</svg>\n`;
const markBody = (color, dimensional = false) => `<path fill="${color}" d="${mark}"/>${dimensional ? faces.map(face => `<path fill="${face.fallback}" d="${face.path}"/>`).join("") : ""}`;

async function main() {
  fs.mkdirSync(assets, { recursive: true });
  fs.mkdirSync(path.join(__dirname, "previews"), { recursive: true });
  const before = path.join(__dirname, "before-wordmark.svg");
  if (!fs.existsSync(before)) fs.copyFileSync(path.join(assets, "stoquify-wordmark.svg"), before);

  // Reuse the repository's licensed Manrope 750 outlines. Optically reduce S to
  // x-height and tighten its advance to form the existing lowercase brand name.
  const outlined = fs.readFileSync(path.join(root, "docs/branding/logos/stoquify-wordmark-color.svg"), "utf8");
  const wordPaths = [...outlined.matchAll(/<path d="([^"]+)" transform="translate\(([\d.]+) 66\) scale\(0.032000 -0.032000\)"/g)].map((match, index) =>
    new Path2D(match[1]).transform({ a: index === 0 ? .026 : .032, b: 0, c: 0, d: index === 0 ? -.0235 : -.032, e: index === 0 ? 0 : Number(match[2]) - 15, f: 48 }).toSVGString()
  );
  if (wordPaths.length !== 8) throw new Error("Expected eight licensed wordmark outlines");
  const width = 260, height = 65;
  const word = wordPaths.join(" ");
  const wordBody = color => `<path fill="${color}" d="${word}"/>`;
  fs.writeFileSync(path.join(root, "components/global/stoquify-logo-artwork.ts"),
    `// Generated by docs/branding/refresh-2026-10-20/build-assets.cjs.\n// Manrope lettering: docs/branding/fonts/Manrope-OFL.txt. No runtime font required.\nexport const STOQUIFY_MARK_PATH = ${JSON.stringify(mark)};\nexport const STOQUIFY_MARK_FACES = ${JSON.stringify(faces, null, 2)} as const;\nexport const STOQUIFY_WORDMARK_PATH = ${JSON.stringify(word)};\nexport const STOQUIFY_WORDMARK_VIEWBOX = "0 0 ${width} ${height}";\nexport const STOQUIFY_WORDMARK_RATIO = ${width / height};\n`);

  const variants = { light: [blue, ink], dark: [blue, "#ffffff"], black: ["#000000", "#000000"], white: ["#ffffff", "#ffffff"] };
  const lockupWidth = 350;
  const wordScale = 258 / width;
  for (const [name, [symbolColor, textColor]] of Object.entries(variants)) {
    const dimensional = name === "light" || name === "dark";
    const lockup = svg(lockupWidth, 80, `<g transform="translate(0 5)">${markBody(symbolColor, dimensional)}</g><g transform="translate(88 ${(80 - height * wordScale) / 2}) scale(${wordScale})">${wordBody(textColor)}</g>`);
    fs.writeFileSync(path.join(assets, `stoquify-logo-${name}.svg`), lockup);
    fs.writeFileSync(path.join(assets, `stoquify-symbol-${name}.svg`), svg(70, 70, markBody(symbolColor, dimensional)));
    await sharp(Buffer.from(lockup)).resize(1050, 240).png().toFile(path.join(__dirname, "previews", `logo-${name}.png`));
  }
  fs.writeFileSync(path.join(assets, "stoquify-wordmark.svg"), fs.readFileSync(path.join(assets, "stoquify-logo-light.svg")));
  fs.writeFileSync(path.join(assets, "stoquify-symbol-flat.svg"), svg(70, 70, markBody(blue)));
  // Existing metadata URL remains stable. Opaque tile preserves contrast in browser tabs.
  const favicon = svg(80, 80, `<rect width="80" height="80" rx="19" fill="${blue}"/><g transform="translate(5 5)">${markBody("#ffffff")}</g>`);
  fs.writeFileSync(path.join(assets, "stoquify-mark.svg"), favicon);
  const appIcon = svg(80, 80, `<rect width="80" height="80" rx="19" fill="${ink}"/><g transform="translate(5 5)">${markBody(blue, true)}</g>`);
  fs.writeFileSync(path.join(assets, "stoquify-app-icon.svg"), appIcon);
  await sharp(Buffer.from(favicon)).resize(180, 180).png().toFile(path.join(assets, "apple-touch-icon.png"));
  await sharp(Buffer.from(appIcon)).resize(512, 512).png().toFile(path.join(assets, "stoquify-app-icon.png"));
  const faviconPngs = await Promise.all([16, 24, 32, 48].map(async size => {
    const png = await sharp(Buffer.from(favicon)).resize(size, size).png().toBuffer();
    fs.writeFileSync(path.join(__dirname, "previews", `favicon-${size}.png`), png);
    return { size, png };
  }));
  const header = Buffer.alloc(6 + faviconPngs.length * 16);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(faviconPngs.length, 4);
  let offset = header.length;
  faviconPngs.forEach(({ size, png }, index) => {
    const entry = 6 + index * 16;
    header[entry] = size;
    header[entry + 1] = size;
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(png.length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += png.length;
  });
  fs.writeFileSync(path.join(root, "public/favicon.ico"), Buffer.concat([header, ...faviconPngs.map(item => item.png)]));
  console.log(`Generated Connect logo: ${wordPaths.length} outlined wordmark paths, ${width}×${height}; SVG variants, app icons and multi-resolution ICO.`);
}

main().catch(error => { console.error(error); process.exitCode = 1; });
