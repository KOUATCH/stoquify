  render(<AccountantWorkDesk locale={locale} />)
  await screen.findByText("Client A")
  let resolveRefresh!: (value: typeof result) => void
  list.mockImplementationOnce(() => new Promise(resolve => { resolveRefresh = resolve }))
  const refresh = screen.getByRole("button", { name: copy[locale].refresh })
  refresh.focus()
  fireEvent.click(refresh)
  expect(refresh).toHaveAttribute("aria-disabled", "true")
  expect(refresh).not.toBeDisabled()
