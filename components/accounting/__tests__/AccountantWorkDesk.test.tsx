it("confirms identity in place without automatically resubmitting or changing the command", async () => {
  accept.mockResolvedValueOnce({ success: false, code: "FRESH_AUTH_REQUIRED" }).mockResolvedValueOnce({ success: true, data: {} })
  const stepUp = stepUpWithPasswordAction as jest.Mock
  stepUp.mockResolvedValueOnce({ success: false }).mockResolvedValueOnce({ success: true })
  render(<AccountantWorkDesk />)
  fireEvent.click(await screen.findByRole("button", { name: /Review response: Client A/ }))
  fireEvent.change(await screen.findByLabelText(/Review conclusion/), { target: { value: "Reviewed against statement" } })
  fireEvent.click(screen.getByRole("checkbox"))
  fireEvent.click(screen.getByRole("button", { name: "Accept evidence response" }))
  const password = await screen.findByLabelText("Current password")
  expect(password).toHaveFocus()
  expect(screen.getByRole("button", { name: "Accept evidence response" })).toBeDisabled()
  fireEvent.change(password, { target: { value: "wrong synthetic password" } })
  fireEvent.click(screen.getByRole("button", { name: "Confirm identity" }))
  expect(await screen.findByText(/Identity could not be confirmed/)).toBeInTheDocument()
  expect(password).toHaveValue("")
  fireEvent.change(password, { target: { value: "correct synthetic password" } })
  fireEvent.click(screen.getByRole("button", { name: "Confirm identity" }))
  expect(await screen.findByText(/Identity confirmed/)).toBeInTheDocument()
  expect(accept).toHaveBeenCalledTimes(1)
  expect(screen.queryByLabelText("Current password")).not.toBeInTheDocument()
  expect(screen.getByRole("button", { name: "Accept evidence response" })).toHaveFocus()
  fireEvent.click(screen.getByRole("button", { name: "Accept evidence response" }))
  expect(await screen.findByText(/Evidence response accepted/)).toBeInTheDocument()
  expect(accept.mock.calls[0][0]).toEqual(accept.mock.calls[1][0])
})
