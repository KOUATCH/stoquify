it("preserves notes on a stale binding, refreshes evidence and requires deliberate review", async () => {
  accept.mockResolvedValueOnce({ success: false, code: "CONFLICT" }).mockResolvedValueOnce({ success: true, data: {} })
  render(<AccountantWorkDesk />)
  fireEvent.click(await screen.findByRole("button", { name: /Review response: Client A/ }))
  fireEvent.change(await screen.findByLabelText(/Review conclusion/), { target: { value: "Reviewed source and response" } })
  fireEvent.click(screen.getByRole("checkbox"))
  const next = { ...replacement, selection: { checklistItemId: "new-receipt", bindingHash: `sha256:${"b".repeat(64)}` } }
  detail.mockResolvedValueOnce({ success: true, data: { ...detailData, replacement: next } })
  fireEvent.click(screen.getByRole("button", { name: "Accept evidence response" }))
  expect(await screen.findByText(/Source evidence changed/)).toBeInTheDocument()
  expect(screen.getByLabelText(/Review conclusion/)).toHaveValue("Reviewed source and response")
  expect(screen.getByRole("checkbox")).not.toBeChecked()
  expect(accept).toHaveBeenCalledTimes(1)
  expect(screen.getByRole("button", { name: "Accept evidence response" })).toBeDisabled()
  fireEvent.click(screen.getByRole("checkbox"))
  fireEvent.click(screen.getByRole("button", { name: "Accept evidence response" }))
  await screen.findByText(/Evidence response accepted/)
  expect(accept.mock.calls[0][0].replacement).toEqual(replacement.selection)
  expect(accept.mock.calls[1][0].replacement).toEqual(next.selection)
})
