import {
  financeX1EvidenceBinding,
  financeX1EvidenceBindingSchema,
} from "../../components/DataTableComponents";
import { evaluateFinanceX1EvidencePreflight, loadFinanceX1ApprovalManifest } from "../finance-x1-evidence-preflight";
import { mkdtempSync, writeFileSync, unlinkSync, rmdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const approvedBinding = financeX1EvidenceBindingSchema.parse({
  ...financeX1EvidenceBinding,
  budgetApproval: {
    status: "approved",
    budgetContractVersion: 1,
    approvalReference: "CTRL-2026-0831-001",
    approvedByUserId: "rds_org_001_compliance_user_product_approver",
    approvedByRole: "product_approver",
    approvedAt: "2026-08-31T10:00:00.000Z",
    scope: "X1-finance-accounting-performance-budgets",
  },
  evidenceAuthorization: {
    status: "approved",
    environment: "non-production",
    credentialApprovalReference: "SEC-2026-0831-001",
    seededDataApprovalReference: "DATA-2026-0831-001",
    authorizedFixtureTenantId: "rds_org_001",
    approvedByUserId: "security-control-owner-user-id",
    approvedAt: "2026-08-31T10:05:00.000Z",
  },
  evidenceStatus: "approved-awaiting-evidence",
  claims: {
    screenshotsAvailable: false,
    measurementsAvailable: false,
    productionBudgetsApproved: true,
  },
});

const readyEnvironment = {
  FINANCE_X1_EVIDENCE_RUN_ID: "finance-x1-20260831-001",
  FINANCE_X1_FOREIGN_TENANT_ID: "rds_org_002",
  PLAYWRIGHT_BASE_URL: "http://127.0.0.1:3000",
  PLAYWRIGHT_FINANCE_X1_STORAGE_STATE:
    "playwright/.auth/finance-x1-external-accountant.json",
};

describe("finance X1 evidence preflight", () => {
  it.each(["product", "evidence"])("rejects a copied local %s approval outside the register exports", (kind) => {
    const root = mkdtempSync(join(tmpdir(), "x1-preflight-copy-"));
    const file = join(root, "copied-approval.json");
    const input = JSON.parse(JSON.stringify(approvedBinding));
    if (kind === "product") input.budgetApproval.approvalReference = "X1-PRODUCT-11111111-1111-4111-8111-111111111111";
    else input.evidenceAuthorization.credentialApprovalReference = "X1-EVIDENCE-11111111-1111-4111-8111-111111111111#credential-use";
    try {
      writeFileSync(file, JSON.stringify(input));
      expect(() => loadFinanceX1ApprovalManifest(root, "copied-approval.json")).toThrow("Choose an approval binding generated by this register");
    } finally { unlinkSync(file); rmdirSync(root); }
  });
  it("blocks the pending checked-in manifest without external inputs", () => {
    const report = evaluateFinanceX1EvidencePreflight(
      financeX1EvidenceBinding,
      {},
    );

    expect(report.status).toBe("blocked");
    expect(report.certificationClaimed).toBe(false);
    expect(report.findings.map((item) => item.id)).toEqual(
      expect.arrayContaining([
        "traceable-approvals",
        "run-id",
        "approved-storage-state",
      ]),
    );
  });

  it("accepts a traceable approved packet and authenticated state reference", () => {
    const report = evaluateFinanceX1EvidencePreflight(
      approvedBinding,
      readyEnvironment,
      {
        inspectStorageState: () => ({
          exists: true,
          nonEmpty: true,
          hasAuthenticatedState: true,
        }),
      },
    );

    expect(report).toMatchObject({
      status: "ready-for-capture",
      blockerCount: 0,
      storageStateConfigured: true,
      certificationClaimed: false,
    });
  });

  it("rejects a production-like browser target", () => {
    const report = evaluateFinanceX1EvidencePreflight(
      approvedBinding,
      {
        ...readyEnvironment,
        PLAYWRIGHT_BASE_URL: "https://app.stoquify.example.com",
      },
      {
        inspectStorageState: () => ({
          exists: true,
          nonEmpty: true,
          hasAuthenticatedState: true,
        }),
      },
    );

    expect(report.findings).toEqual(
      expect.arrayContaining([
        expect.objectContaining({ id: "non-production-target" }),
      ]),
    );
  });
});
