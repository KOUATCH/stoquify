import fs from "node:fs"
import path from "node:path"
import { auditOpeningFixture, scaled, stockIssues, type OpeningFixture } from "./fixtures/opening-position-contract"

const fixturePath = path.join(__dirname, "fixtures/opening-position-source.json")
const load = (): OpeningFixture => JSON.parse(fs.readFileSync(fixturePath, "utf8"))
const { basis: _basis, ...expected } = JSON.parse(fs.readFileSync(path.join(__dirname, "fixtures/opening-position-controls.json"), "utf8"))

it("reconciles against a separately hand-calculated control sheet", () => {
  const result = auditOpeningFixture(load())
  expect(result.issues).toEqual([])
  expect(result.controls).toEqual(expected)
  // Explicit arithmetic oracle, not generated by the validator under test:
  // stock 1000+500+1000+500=3000; assets 3000+1200+500=4700;
  // liabilities 700 plus equity 4000=4700; quantities never sum EA and KG.
  expect(result.controls.stockValueMinor).toBe("300000")
  expect(result.controls.ledgerDebitMinor).toBe("470000")
  expect(result.controls.ledgerCreditMinor).toBe("470000")
})
it("retains each rejected source row and its independently stated rejection", () => {
  const f = load()
  expect(f.rejectedStockRows).toHaveLength(3)
  for (const rejected of f.rejectedStockRows) expect(stockIssues(f, rejected.row)).toContain(rejected.expectedIssue)
})
it("exposes an unbalanced opening ledger", () => {
  const f = load(); f.ledger[4].amount = "3999.99"
  expect(auditOpeningFixture(f).issues).toContain("LEDGER_IMBALANCE")
})
it("detects changed approved source totals even when the replacement remains internally balanced", () => {
  const f = load()
  f.stock[0].quantity = "9.000"; f.stock[0].sourceValue = "900.00"
  f.ledger[0].amount = "2900.00"; f.ledger[4].amount = "3900.00"
  const result = auditOpeningFixture(f)
  expect(result.issues).toEqual([])
  // Passing internal consistency is insufficient: retained independent controls
  // must match too. Never regenerate the expected sheet from changed input.
  expect(result.controls).not.toEqual(expected)
  expect(result.controls.stockValueMinor).toBe("290000")
  expect(expected.stockValueMinor).toBe("300000")
})
it("exposes a duplicated opening posting even when debits and credits remain balanced", () => {
  const f = load()
  f.ledger.push({ ...f.ledger[0], sourceId: "duplicate-stock-posting", postingOwner: "STOCK_AUTO_LEDGER" })
  f.ledger.push({ ...f.ledger[4], sourceId: "duplicate-offset", amount: "3000.00", postingOwner: "STOCK_AUTO_LEDGER" })
  const result = auditOpeningFixture(f)
  expect(result.controls.ledgerDebitMinor).toBe(result.controls.ledgerCreditMinor)
  expect(result.issues).toEqual(expect.arrayContaining(["DOUBLE_POSTING_RISK", "DUPLICATE_POSTING_COVERAGE", "CONTROL_TIE_OUT"]))
})
it("detects a balanced but incorrect control-account allocation", () => {
  const f = load(); f.ledger[0].amount = "2999.00"; f.ledger[2].amount = "501.00"
  expect(auditOpeningFixture(f).issues).toEqual(expect.arrayContaining(["CONTROL_TIE_OUT", "COVERAGE_VALUE_DISCREPANCY"]))
})
it.each(["stock", "openItems", "ledger"] as const)("rejects duplicate source identifiers in %s", table => {
  const f = load(); (f[table] as Array<unknown>).push({ ...f[table][0] })
  expect(auditOpeningFixture(f).issues).toContain("DUPLICATE_SOURCE_ID")
})
it("detects duplicate position and document under different source identifiers", () => {
  const f = load(); f.stock.push({ ...f.stock[0], sourceId: "different-id" }); f.openItems.push({ ...f.openItems[0], sourceId: "different-ar" })
  expect(auditOpeningFixture(f).issues).toEqual(expect.arrayContaining(["DUPLICATE_STOCK_POSITION", "DUPLICATE_DOCUMENT"]))
})
it.each([
  ["quantity", "11.000", "VALUE_DISCREPANCY"], ["sourceValue", "1000.01", "VALUE_DISCREPANCY"],
  ["unitCost", "100.001", "PRECISION"], ["quantity", "1.0001", "PRECISION"],
  ["quantity", "0.000", "INVALID_QUANTITY"], ["organizationId", "foreign", "WRONG_TENANT"],
  ["locationId", "foreign-site", "WRONG_LOCATION"], ["itemId", "foreign-item", "UNKNOWN_ITEM"],
  ["unit", "KG", "WRONG_UNIT"], ["reviewId", "missing", "MISSING_REVIEW"],
  ["ledgerEffect", "AUTO_POSTED", "DOUBLE_POSTING_RISK"],
])("rejects stock %s mismatch", (field, value, issue) => {
  const f = load(); Object.assign(f.stock[0], { [field]: value })
  expect(auditOpeningFixture(f).issues).toContain(issue)
})
it.each(["stock", "openItems", "ledger"] as const)("rejects foreign tenant in %s", table => {
  const f = load(); f[table][0].organizationId = "foreign"
  expect(auditOpeningFixture(f).issues).toContain("WRONG_TENANT")
})
it("detects reused foreign tenant masters, independent of row IDs", () => {
  const f = load(); f.locations[0].organizationId = "foreign"; f.items[0].organizationId = "foreign"
  expect(auditOpeningFixture(f).issues).toEqual(expect.arrayContaining(["WRONG_TENANT", "WRONG_LOCATION", "UNKNOWN_ITEM"]))
})
it.each([
  ["outstandingAmount", "1200.01", "OPEN_ITEM_DISCREPANCY"], ["settledBeforeCutover", "1501.00", "OPEN_ITEM_DISCREPANCY"],
  ["currency", "EUR", "CURRENCY_MISMATCH"], ["counterpartyId", "supplier-a", "WRONG_COUNTERPARTY"],
  ["sourceDate", "2026-10-01", "DOCUMENT_DATE"],
])("rejects opening receivable %s mismatch", (field, value, issue) => {
  const f = load(); Object.assign(f.openItems[0], { [field]: value })
  expect(auditOpeningFixture(f).issues).toContain(issue)
})
it("keeps AP obligation positive while the general-ledger control is credit", () => {
  const f = load(); expect(auditOpeningFixture(f).controls.payableMinor).toBe("70000")
  f.ledger[3].side = "DEBIT"
  expect(auditOpeningFixture(f).issues).toEqual(expect.arrayContaining(["ACCOUNT_SIDE", "CONTROL_TIE_OUT"]))
})
it("requires exact retained coverage, not just balanced aggregate amounts", () => {
  const f = load(); f.ledger[0].covers = ["stock-001", "stock-002", "stock-003", "unknown-source"]
  expect(auditOpeningFixture(f).issues).toEqual(expect.arrayContaining(["WRONG_POSTING_COVERAGE", "MISSING_POSTING_COVERAGE"]))
})
it("does not permit the maker to be the synthetic reviewer", () => {
  const f = load(); f.review.reviewerId = f.makerId
  expect(auditOpeningFixture(f).issues).toContain("REVIEW_SEPARATION")
})
it("does not treat a pending reviewer decision as approval", () => {
  const f = load(); f.review.decision = "PENDING"
  expect(auditOpeningFixture(f).issues).toContain("REVIEW_SEPARATION")
})
it("rejects inconsistent local and UTC cutover dates", () => {
  const f = load(); f.cutoverAt = "2026-10-01T00:00:00.000Z"
  expect(auditOpeningFixture(f).issues).toContain("CUTOVER_MISMATCH")
})
it("keeps rejected rows out of accepted opening totals", () => {
  const f = load(); f.stock.push(f.rejectedStockRows[0].row)
  expect(auditOpeningFixture(f).issues).toContain("REJECTED_ROW_INCLUDED")
})
it("checks literal precision without binary floating-point arithmetic", () => {
  expect(scaled("0.01", 2)).toBe(1n); expect(scaled("1.250", 3)).toBe(1250n)
  expect(scaled("9007199254740993.25", 2)).toBe(900719925474099325n)
  for (const value of ["1e3", "NaN", "Infinity", "-1", "1.001"]) expect(() => scaled(value, 2)).toThrow("PRECISION")
})
it("makes proposal rounding explicit with an independent half-cent example", () => {
  const f = load(); const row = { ...f.stock[2], quantity: "0.001", unitCost: "5.00", sourceValue: "0.01" }
  expect(stockIssues(f, row)).toEqual([])
  expect(stockIssues(f, { ...row, sourceValue: "0.00" })).toContain("VALUE_DISCREPANCY")
})
