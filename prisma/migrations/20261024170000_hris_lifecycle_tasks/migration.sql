CREATE TABLE hris_lifecycle_tasks (
 id text PRIMARY KEY,
 "organizationId" text NOT NULL,
 "employeeId" text NOT NULL,
 "requestId" text NOT NULL,
 "approvalEventId" text NOT NULL,
 "lifecycleType" text NOT NULL,
 code text NOT NULL,
 "ownerId" text NOT NULL,
 "reviewerId" text NOT NULL,
 "effectiveAt" timestamptz NOT NULL,
 "dueAt" timestamptz NOT NULL,
 status text NOT NULL DEFAULT 'OPEN',
 "sourceState" text NOT NULL DEFAULT 'ACTIVE',
 revision integer NOT NULL DEFAULT 1,
 policy jsonb NOT NULL,
 template jsonb NOT NULL,
 history jsonb NOT NULL DEFAULT '[]',
 "submittedById" text,
 "evidenceReference" text,
 "documentId" text,
 "outcomeKind" text,
 "createdAt" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 "updatedAt" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT hris_task_employee_fk FOREIGN KEY ("organizationId","employeeId") REFERENCES payroll_employees("organizationId",id) ON DELETE RESTRICT,
 CONSTRAINT hris_task_identity UNIQUE ("organizationId","requestId",code),
 CONSTRAINT hris_task_state CHECK(status IN ('OPEN','FAILED','AWAITING_REVIEW','COMPLETED','CANCELLED')),
 CONSTRAINT hris_task_source CHECK("sourceState" IN ('ACTIVE','CANCELLED')),
 CONSTRAINT hris_task_kind CHECK(code IN ('HR_PREPARATION','APPLICATION_ACCESS','EXTERNAL_ACCESS','ASSETS')),
 CONSTRAINT hris_task_independent CHECK("ownerId"<>"reviewerId"),
 CONSTRAINT hris_task_revision CHECK(revision>0)
);
CREATE INDEX hris_task_owner_due ON hris_lifecycle_tasks("organizationId","ownerId",status,"dueAt");
CREATE INDEX hris_task_reviewer_due ON hris_lifecycle_tasks("organizationId","reviewerId",status,"dueAt");
